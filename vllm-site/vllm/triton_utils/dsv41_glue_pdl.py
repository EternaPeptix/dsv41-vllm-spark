"""DSV41_GLUE_PDL (climb r1, lever G07 stage 1): programmatic dependent launch for the hot non-PDL Triton glue kernels.

GENERATED by r1-pdl/scripts/gen_glue_pdl.py from the live kernel sources; do not edit by hand.

Lives in vllm/triton_utils/ because that package is light and already initialised by every caller (importing a module
under vllm.models.deepseek_v41 from fp8_utils at import time would import the whole model package: circular import).
Only imported when DSV41_GLUE_PDL is set (each patched call site reads the env var at import and imports this module
inside its gated branch). With the flag unset none of this code exists in the process.

Every kernel below is a verbatim copy of the live kernel (same decorator, signature, body, launch grid, constexprs,
num_warps / num_stages / enable_fp_fusion), with two kinds of change, all tagged `# r1-pdl`:
  1. `tl.extra.cuda.gdc_wait()` (PTX griddepcontrol.wait) is the first statement of every kernel body: the kernel
     reads and writes no global memory before all prerequisite grids have completed and their memory is visible.
  2. the launch passes `launch_pdl=True` (cudaLaunchAttributeProgrammaticStreamSerialization), so the grid may be
     scheduled while its predecessor drains; in a captured CUDA graph the edge becomes programmatic.
  3. optional (token `trig`): the two statically paired producers (_sm120_wo_a_partial -> _sm120_wo_a_reduce,
     _dsv41_fp_plan_kernel -> _dsv41_fp_scatter_kernel) call gdc_launch_dependents() right AFTER their own wait,
     so the paired consumer (which also waits at entry) can be scheduled early. No other kernel triggers early;
     everything else triggers implicitly at grid completion, exactly as today.

Flag grammar (comma separated, case-insensitive):
  unset | 0 | off          off (default)
  1 | all | on             all families: proj, woa, silu, gather, fp, topk
  <family>[,<family>...]   a subset, e.g. "proj,woa"
  trig                     add the paired early triggers (with a family list or with all)
Unknown tokens raise at import (fail-closed boot error rather than a silently different arm).
"""

from __future__ import annotations

import logging
import os

logger = logging.getLogger("vllm.dsv41_glue_pdl")

FAMILIES = ("proj", "woa", "silu", "gather", "fp", "topk")


def parse(raw: str) -> tuple[frozenset, bool]:
    toks = [t for t in (x.strip().lower() for x in (raw or "").split(",")) if t]
    if not toks or toks == ["0"] or toks == ["off"]:
        return frozenset(), False
    fams, trig = set(), False
    for t in toks:
        if t in ("1", "all", "on"):
            fams.update(FAMILIES)
        elif t == "trig":
            trig = True
        elif t in FAMILIES:
            fams.add(t)
        else:
            raise ValueError(f"DSV41_GLUE_PDL: unknown token {t!r} (families {FAMILIES}, all, trig)")
    if trig and not fams:
        fams.update(FAMILIES)
    return frozenset(fams), trig


_FAMS, _TRIG = parse(os.environ.get("DSV41_GLUE_PDL", "0"))
TRIGGER = 1 if _TRIG else 0
_SUPPORTED = None
_logged = set()


def enabled(family: str) -> bool:
    """True when this family runs the PDL kernels (each call site reads this once, at its own import)."""
    if family not in FAMILIES:
        raise ValueError(family)
    on = family in _FAMS
    if on and family not in _logged:
        _logged.add(family)
        logger.warning("DSV41_GLUE_PDL: %s kernels launch with PDL (gdc_wait at entry)%s", family,
                       ", paired early trigger" if (_TRIG and family in ("woa", "fp")) else "")
    return on


# ---- end of the pure-Python part (tests exec everything above this line) ----


def _check() -> None:
    """First launch only: PDL must be supported (GB10 sm_121 is); fail closed and loud otherwise."""
    global _SUPPORTED
    if _SUPPORTED is None:
        from vllm.platforms import current_platform
        _SUPPORTED = bool(current_platform.is_cuda() and current_platform.is_arch_support_pdl())
    if not _SUPPORTED:
        raise RuntimeError("DSV41_GLUE_PDL is set but this device has no programmatic dependent launch; unset it")


