# ---- family 'proj': _proj_rows, verbatim from vllm/models/deepseek_v41/nvidia/dsv41_oblit.py ----
@triton.jit
def _proj_rows(X, Y, D, stride_x, stride_y, H, BLOCK: tl.constexpr):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    row = tl.program_id(0).to(tl.int64)
    offs = tl.arange(0, BLOCK)
    m = offs < H
    x = tl.load(X + row * stride_x + offs, mask=m, other=0.0).to(tl.float32)
    d = tl.load(D + offs, mask=m, other=0.0)
    s = tl.sum(x * d, axis=0)
    tl.store(Y + row * stride_y + offs, (x - s * d).to(Y.dtype.element_ty), mask=m)


# ---- family 'woa': _sm120_wo_a_partial, verbatim from vllm/models/deepseek_v4/nvidia/ops/sonar_bf16_bmm.py ----
@triton.jit
def _sm120_wo_a_partial(
    A,
    W,
    S,
    P,
    M,
    G: tl.constexpr,
    N: tl.constexpr,
    K: tl.constexpr,
    ASG: tl.int64,
    ASM: tl.int64,
    ASK: tl.int64,
    CHUNK: tl.constexpr,
    FP8W: tl.constexpr, G07_TRIGGER: tl.constexpr = 0,  # r1-pdl
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    if G07_TRIGGER:  # r1-pdl
        tl.extra.cuda.gdc_launch_dependents()  # r1-pdl: after the wait (transitive completion)
    group = tl.program_id(1) // tl.cdiv(M, 16)
    row = tl.program_id(1) % tl.cdiv(M, 16) * 16 + tl.arange(0, 16)
    col = tl.program_id(0) * 64 + tl.arange(0, 64)
    split = tl.program_id(2)
    acc = tl.zeros((16, 64), tl.float32)
    for step in range(CHUNK // 128):
        k = split * CHUNK + step * 128 + tl.arange(0, 128)
        a = tl.load(
            A + group * ASG + row[:, None] * ASM + k[None, :] * ASK,
            row[:, None] < M,
            other=0,
        )
        # N % 64 == 0 and K % (128 * splits) == 0 are checked by the caller,
        # so weight/scale tiles are always in bounds (no mask; fp8 loads cannot
        # take an integer `other`).
        if FP8W:
            q = tl.load(W + group * N * K + col[None, :] * K + k[:, None])
            e = tl.load(
                S + group * N * (K // 32) + col[None, :] * (K // 32) + k[:, None] // 32
            )
            # Same arithmetic as dequant_mxfp8_to_bf16: fp32 q * 2^(e-127),
            # rounded once to bf16 -> bit-identical to the live bf16 weight.
            # 2^(e-127) is built from its bits (e in 1..254), not ex2.approx.
            scl = (e.to(tl.int32) << 23).to(tl.float32, bitcast=True)
            w = (q.to(tl.float32) * scl).to(tl.bfloat16)
        else:
            w = tl.load(W + group * N * K + col[None, :] * K + k[:, None])
        acc = tl.dot(a, w, acc)
    tl.store(
        P + ((split * G + group) * M + row[:, None]) * N + col[None, :],
        acc,
        (row[:, None] < M) & (col[None, :] < N),
    )


# ---- family 'woa': _sm120_wo_a_reduce, verbatim from vllm/models/deepseek_v4/nvidia/ops/sonar_bf16_bmm.py ----
@triton.jit
def _sm120_wo_a_reduce(
    P, OUT, M, G: tl.constexpr, N: tl.constexpr, SPLITS: tl.constexpr
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    pos = tl.program_id(0) * 256 + tl.arange(0, 256)
    split = tl.arange(0, SPLITS)
    total = G * M * N
    partial = tl.load(P + split[:, None] * total + pos[None, :], pos[None, :] < total, other=0)
    value = tl.sum(partial, axis=0)
    group, row, col = pos // (M * N), pos // N % M, pos % N
    tl.store(OUT + (row * G + group) * N + col, value, pos < total)


# ---- family 'silu': _silu_mul_quant_fp8_packed_kernel, verbatim from vllm/model_executor/layers/quantization/utils/fp8_utils.py ----
@triton.jit
def _silu_mul_quant_fp8_packed_kernel(
    input_ptr,
    output_q_ptr,
    output_scale_ptr,
    expert_ends_ptr,
    M,
    input_stride_m,
    output_q_stride_m,
    output_scale_stride_k,
    clamp_limit,
    alpha,
    beta,
    N: tl.constexpr,
    GROUPS_PER_ROW: tl.constexpr,
    PACKS_PER_ROW: tl.constexpr,
    fp8_min: tl.constexpr,
    fp8_max: tl.constexpr,
    GROUP_SIZE: tl.constexpr,
    PACKS_PER_CTA: tl.constexpr,
    BLOCK_M: tl.constexpr,
    HAS_CLAMP: tl.constexpr,
    EXPERT_ALIGNMENT: tl.constexpr,
    PDL_TRIGGER: tl.constexpr = 0,
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    GROUPS_PER_PACK: tl.constexpr = 4
    hidden_size: tl.constexpr = N // 2
    # pd-pdl (DSV41_MOE_PDL_TRIGGER, default 0 = unchanged code): let the PDL-launched FC2 grid
    # start its pre-wait weight prologue while this kernel still runs. FC2 still waits
    # (griddepcontrol.wait) before reading anything written here.
    if PDL_TRIGGER == 1:
        tl.extra.cuda.gdc_launch_dependents()

    pack_tile = tl.program_id(0)
    row_start = tl.program_id(1).to(tl.int64) * BLOCK_M
    row_step = tl.num_programs(1).to(tl.int64) * BLOCK_M

    if EXPERT_ALIGNMENT:
        expert = tl.program_id(2)
        previous_end = tl.load(expert_ends_ptr + expert - 1, expert > 0, other=0)
        expert_start = tl.cdiv(previous_end, EXPERT_ALIGNMENT) * EXPERT_ALIGNMENT
        row_start += expert_start.to(tl.int64)
        M = tl.load(expert_ends_ptr + expert)

    groups_per_cta: tl.constexpr = PACKS_PER_CTA * GROUPS_PER_PACK
    elems_per_cta: tl.constexpr = groups_per_cta * GROUP_SIZE
    col_start = pack_tile * elems_per_cta
    col_offsets = tl.arange(0, elems_per_cta)
    row_offsets = tl.arange(0, BLOCK_M)
    pack_offsets = tl.arange(0, PACKS_PER_CTA)

    input_col_mask = (col_start + col_offsets) < hidden_size
    output_col_mask = (col_start + col_offsets) < (GROUPS_PER_ROW * GROUP_SIZE)

    # persistent with grid_m-stride loop
    while row_start < M:
        rows = row_start + row_offsets
        row_mask = rows < M
        input_row_start = rows[:, None] * input_stride_m
        output_row_start = rows[:, None] * output_q_stride_m

        gate_flat = tl.load(
            input_ptr + input_row_start + col_start + col_offsets[None, :],
            mask=row_mask[:, None] & input_col_mask[None, :],
            other=0.0,
        )
        up_flat = tl.load(
            input_ptr
            + input_row_start
            + hidden_size
            + col_start
            + col_offsets[None, :],
            mask=row_mask[:, None] & input_col_mask[None, :],
            other=0.0,
        )

        gate = tl.reshape(gate_flat, (BLOCK_M, groups_per_cta, GROUP_SIZE)).to(
            tl.float32
        )
        up = tl.reshape(up_flat, (BLOCK_M, groups_per_cta, GROUP_SIZE)).to(tl.float32)

        if HAS_CLAMP:
            gate = tl.minimum(gate, clamp_limit)
            up = tl.clamp(up, -clamp_limit, clamp_limit)

        # Unified gated activation: silu == swigluoai with alpha=1, beta=0.
        #   glu = gate * sigmoid(alpha * gate); y = (up + beta) * glu
        glu = gate / (1.0 + tl.exp(-gate * alpha))
        y = (up + beta) * glu
        # Round through bf16 to match unfused precision path
        y = y.to(tl.bfloat16).to(tl.float32)

        absmax = tl.max(tl.abs(y), axis=2)
        scale_raw = tl.maximum(absmax / fp8_max, 1e-10)
        exponent = tl.ceil(tl.log2(scale_raw))
        scale = tl.math.exp2(exponent)

        y_q = tl.clamp(y / scale[:, :, None], fp8_min, fp8_max)

        y_q_flat = tl.reshape(y_q, (BLOCK_M, elems_per_cta))
        tl.store(
            output_q_ptr + output_row_start + col_start + col_offsets[None, :],
            y_q_flat.to(output_q_ptr.dtype.element_ty),
            mask=row_mask[:, None] & output_col_mask[None, :],
        )

        scale_byte = tl.clamp(exponent + 127.0, 0.0, 255.0).to(tl.int32)
        scale_bytes = tl.reshape(scale_byte, (BLOCK_M, PACKS_PER_CTA, GROUPS_PER_PACK))
        shifts = tl.arange(0, GROUPS_PER_PACK) * 8
        packed_scale = tl.sum(scale_bytes << shifts[None, None, :], axis=2)

        scale_pack = pack_tile * PACKS_PER_CTA + pack_offsets
        scale_ptrs = (
            output_scale_ptr
            + scale_pack[None, :] * output_scale_stride_k
            + rows[:, None]
        )
        tl.store(
            scale_ptrs,
            packed_scale,
            mask=row_mask[:, None] & (scale_pack[None, :] < PACKS_PER_ROW),
        )

        row_start += row_step
    if PDL_TRIGGER == 2:
        tl.extra.cuda.gdc_launch_dependents()


# ---- family 'gather': _gated_gather, verbatim from home/dsv41-fc2/fc2_status_gated_gather_trial.py ----
@triton.jit
def _gated_gather(
    total_token_num, input_tensor, input_stride0, input_stride1,
    recv_topk_ids, ids_stride0, ids_stride1,
    recv_topk_weight, weights_stride0, weights_stride1,
    input_index, index_stride0, index_stride1,
    output_tensor, output_stride0, output_stride1,
    step_status, topk_num: tl.constexpr, BLOCK_D: tl.constexpr,
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    cur_block = tl.program_id(0)
    start_cur_token = tl.program_id(1)
    grid_num = tl.num_programs(1)
    # The status writer must finish on this stream, or be joined by a CUDA
    # event, before launch. Status must remain stable until this gather finishes.
    ok = (tl.load(step_status) & 11) == 0
    for cur_token in range(start_cur_token, total_token_num, grid_num):
        off_d = tl.arange(0, BLOCK_D)
        accumulator = tl.zeros([BLOCK_D], dtype=tl.float32)
        if ok:
            # Keep the normal source's loop and arithmetic, but do not even
            # read top-k indices or partial FC2 output on a failed status.
            for topk_index in range(0, topk_num):
                expert_id = tl.load(recv_topk_ids + cur_token * ids_stride0 + topk_index * ids_stride1)
                if expert_id >= 0:
                    source_index = tl.load(input_index + cur_token * index_stride0 + topk_index * index_stride1)
                    weight = tl.load(recv_topk_weight + cur_token * weights_stride0 + topk_index * weights_stride1)
                    value = tl.load(input_tensor + source_index.to(tl.int64) * input_stride0 +
                                    cur_block * BLOCK_D + off_d * input_stride1)
                    accumulator += value.to(tl.float32) * weight
        # Zeros on failure are placeholders only; the entire step and any
        # affected state must be discarded before anything is published.
        tl.store(output_tensor + tl.cast(cur_token, tl.int64) * output_stride0 +
                 cur_block * BLOCK_D + off_d * output_stride1,
                 accumulator.to(output_tensor.dtype.element_ty))


# ---- family 'fp': _dsv41_fp_plan_kernel, verbatim from vllm/model_executor/layers/fused_moe/deep_gemm_utils.py ----
@triton.jit
def _dsv41_fp_plan_kernel(
    topk_ids,
    ids_stride0,
    ids_stride1,
    cursor,          # [E] int32 out: 32-aligned expert start (advanced to the live end by the scatter kernel)
    layout,          # [M_sum] int32 out: -1
    sfp,             # packed int32 scales, element (row r, pack p) at sfp + p * mn_aligned + r: 0
    M,
    M_sum,
    mn_aligned,
    E: tl.constexpr,
    TOPK: tl.constexpr,
    ALIGN: tl.constexpr,
    PACKS: tl.constexpr,
    SLOTS: tl.constexpr,
    E_PAD: tl.constexpr,
    FILL_ROWS: tl.constexpr, G07_TRIGGER: tl.constexpr = 0,  # r1-pdl
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    if G07_TRIGGER:  # r1-pdl
        tl.extra.cuda.gdc_launch_dependents()  # r1-pdl: after the wait (transitive completion)
    pid = tl.program_id(0)
    r = pid * FILL_ROWS + tl.arange(0, FILL_ROWS)
    rm = r < M_sum
    tl.store(layout + r, tl.full([FILL_ROWS], -1, tl.int32), mask=rm)
    zero = tl.zeros([FILL_ROWS], dtype=tl.int32)
    for p in tl.static_range(PACKS):
        tl.store(sfp + p * mn_aligned + r, zero, mask=rm)
    if pid == 0:
        s = tl.arange(0, SLOTS)
        sm = s < M * TOPK
        t = s // TOPK
        k = s % TOPK
        ids = tl.load(topk_ids + t * ids_stride0 + k * ids_stride1, mask=sm, other=-1).to(tl.int32)
        valid = sm & (ids >= 0) & (ids < E)
        cnt = tl.histogram(tl.where(valid, ids, E), E_PAD)
        b = tl.arange(0, E_PAD)
        cnt = tl.where(b < E, cnt, 0)
        aligned = (cnt + ALIGN - 1) // ALIGN * ALIGN
        start = tl.cumsum(aligned, axis=0) - aligned
        tl.store(cursor + b, start.to(tl.int32), mask=b < E)


# ---- family 'fp': _dsv41_fp_scatter_kernel, verbatim from vllm/model_executor/layers/fused_moe/deep_gemm_utils.py ----
@triton.jit
def _dsv41_fp_scatter_kernel(
    topk_ids,
    ids_stride0,
    ids_stride1,
    aq_words,        # [M, H/4] int32 view of the FP8 rows
    aq_row_words,
    sf_bits,         # [M, SF_K] int32 view of the fp32 scales (any strides)
    sf_stride0,
    sf_stride1,
    cursor,
    out_words,       # [M_sum, H/4] int32 view of the permuted FP8 rows
    out_row_words,
    sfp,
    mn_aligned,
    layout,
    inv_perm,
    inv_stride0,
    inv_stride1,
    E: tl.constexpr,
    TOPK: tl.constexpr,
    H_WORDS: tl.constexpr,
    H_BLOCK: tl.constexpr,
    SF_K: tl.constexpr,
    PACKS: tl.constexpr,
    PACKS_PAD: tl.constexpr,
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    slot = tl.program_id(0)
    t = slot // TOPK
    k = slot % TOPK
    e = tl.load(topk_ids + t * ids_stride0 + k * ids_stride1).to(tl.int32)
    if (e >= 0) & (e < E):
        dest = tl.atomic_add(cursor + e, 1)
        tl.store(inv_perm + t * inv_stride0 + k * inv_stride1, dest)
        tl.store(layout + dest, e)
        w = tl.arange(0, H_BLOCK)
        wm = w < H_WORDS
        row = tl.load(aq_words + t.to(tl.int64) * aq_row_words + w, mask=wm)
        tl.store(out_words + dest.to(tl.int64) * out_row_words + w, row, mask=wm)
        p = tl.arange(0, PACKS_PAD)
        pm = p < PACKS
        base = sf_bits + t.to(tl.int64) * sf_stride0
        g0 = p * 4
        v0 = tl.load(base + g0 * sf_stride1, mask=pm & (g0 < SF_K), other=0).to(tl.uint32, bitcast=True)
        v1 = tl.load(base + (g0 + 1) * sf_stride1, mask=pm & (g0 + 1 < SF_K), other=0).to(tl.uint32, bitcast=True)
        v2 = tl.load(base + (g0 + 2) * sf_stride1, mask=pm & (g0 + 2 < SF_K), other=0).to(tl.uint32, bitcast=True)
        v3 = tl.load(base + (g0 + 3) * sf_stride1, mask=pm & (g0 + 3 < SF_K), other=0).to(tl.uint32, bitcast=True)
        packed = (v0 >> 23) | (v1 >> 15) | (v2 >> 7) | (v3 << 1)
        tl.store(sfp + p * mn_aligned + dest, packed.to(tl.int32, bitcast=True), mask=pm)


# ---- family 'topk': _compute_global_topk_indices_and_lens_kernel, verbatim from vllm/models/deepseek_v41/common/ops/cache_utils.py ----
@triton.jit
def _compute_global_topk_indices_and_lens_kernel(
    global_topk_indices_ptr,
    global_topk_indices_stride: tl.constexpr,
    topk_lens_ptr,
    topk_indices_ptr,
    topk_indices_stride: tl.constexpr,
    topk: tl.constexpr,
    token_to_req_indices_ptr,
    block_table_ptr,
    block_table_stride: tl.constexpr,
    block_size: tl.constexpr,
    is_valid_token_ptr,
    TRITON_BLOCK_SIZE: tl.constexpr,
):
    tl.extra.cuda.gdc_wait()  # r1-pdl: no global memory access above this line
    token_idx = tl.program_id(0)
    is_valid_token = tl.load(is_valid_token_ptr + token_idx)
    req_idx = tl.load(token_to_req_indices_ptr + token_idx)

    count = tl.zeros((), dtype=tl.int32)
    for i in range(0, topk, TRITON_BLOCK_SIZE):
        offset = i + tl.arange(0, TRITON_BLOCK_SIZE)
        mask = offset < topk

        local_idx = tl.load(
            topk_indices_ptr + token_idx * topk_indices_stride + offset,
            mask=mask,
            other=-1,
        )
        is_valid = local_idx >= 0

        block_indices = local_idx // block_size
        block_numbers = tl.load(
            block_table_ptr + req_idx * block_table_stride + block_indices,
            mask=mask & is_valid,
        )
        block_offsets = local_idx % block_size

        slot_ids = block_numbers * block_size + block_offsets
        slot_ids = tl.where(is_valid, slot_ids, -1)
        tl.store(
            global_topk_indices_ptr + token_idx * global_topk_indices_stride + offset,
            slot_ids,
            mask=mask,
        )
        count += tl.sum(is_valid.to(tl.int32), axis=0)

    # Zero out length for padding tokens.
    tl.store(topk_lens_ptr + token_idx, tl.where(is_valid_token, count, 0))



